        ctx.move_to(sx - 24, sy_top + 42)
        ctx.line_to(sx - 12, sy_top + 50)
        ctx.line_to(sx - 24, sy_top + 58)
        ctx.stroke()

        ctx.move_to(sx + 24, sy_top + 42)
        ctx.line_to(sx + 12, sy_top + 50)
        ctx.line_to(sx + 24, sy_top + 58)
        ctx.stroke()

