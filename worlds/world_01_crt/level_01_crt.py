    base_x = 120.0 - (cam_x - 640.0) * 0.3
    base_y = 960.0 - (cam_y - 540.0) * 0.3

    ctx.save()
    ctx.set_source_rgba(0.00, 0.08, 0.03, 0.85)
    ctx.rectangle(base_x - 12, base_y - 28, 580, 75)
    ctx.fill()

    ctx.set_source_rgba(PHOSPHOR_MID[0], PHOSPHOR_MID[1], PHOSPHOR_MID[2], 0.65)
    ctx.set_line_width(1.4)
    ctx.rectangle(base_x - 12, base_y - 28, 580, 75)
    ctx.stroke()

    ctx.select_font_face("DejaVu Sans Mono", cairo.FONT_SLANT_NORMAL, cairo.FONT_WEIGHT_BOLD)
    ctx.set_font_size(16.0)
    ctx.set_source_rgba(PHOSPHOR_PEAK[0], PHOSPHOR_PEAK[1], PHOSPHOR_PEAK[2], 0.98)
    prompt_str = f"stardino@crt:~$ {prompt['typed']}"
    ctx.move_to(base_x, base_y)
    ctx.show_text(prompt_str)

    # Blinking block cursor
    if int(t * 3.0) % 2 == 0:
        ext = ctx.text_extents(prompt_str)
        ctx.rectangle(base_x + ext.x_advance + 4, base_y - 14, 11, 16)
        ctx.fill()

