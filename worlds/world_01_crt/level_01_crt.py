def draw_pixel_pipe_and_particles(ctx: cairo.Context, particles: List[Dict[str, Any]], pipe_dict: Optional[Dict[str, Any]], cam_x: float, cam_y: float, t: float):
    """Draws the phosphor pixel particles condensing into the complete 16-Bit Green Warp Portal."""
    if not particles:
        return

    ctx.save()
    # Color palette for the 16-Bit Green Warp Portal blocks
    pipe_colors = {
        "border": (0.01, 0.14, 0.05),
        "peak":   (0.62, 1.00, 0.74),
        "bright": (0.18, 0.94, 0.46),
        "mid":    (0.02, 0.70, 0.28),
        "dim":    (0.00, 0.42, 0.16),
    }

    for p in particles:
        sx = p["x"] - cam_x + W * 0.5
        sy = p["y"] - cam_y + H * 0.5
        alpha = p["alpha"]
        if alpha < 0.01 or sx < -20 or sx > W + 20 or sy < -20 or sy > H + 20:
            continue
        col = pipe_colors.get(p["color_type"], PHOSPHOR_PEAK)
        ctx.set_source_rgba(col[0], col[1], col[2], alpha)
        # Slightly overlapping 6.4x6.4 blocks when locked so the assembled pipe has zero seams!
        sz = 6.4 if p.get("locked") else 7.2
        ctx.rectangle(sx - sz * 0.5, sy - sz * 0.5, sz, sz)
        ctx.fill()

    # Once pipe assembly reaches >= 85%, reinforce crisp 16-bit pipe rim collar, dark opening slot & warp glow
    if pipe_dict and pipe_dict.get("progress", 0.0) > 0.85:
        prog = pipe_dict["progress"]
        rim_alpha = (prog - 0.85) / 0.15
        px_center = pipe_dict["x"] - cam_x + W * 0.5
        py_top = pipe_dict["top_y"] - cam_y + H * 0.5
        py_bot = pipe_dict["bottom_y"] - cam_y + H * 0.5

        rim_w = 168.0
        rim_h = 60.0
        tube_w = 144.0

        # Subtle outer phosphor glow around the completed pipe
        ctx.set_source_rgba(PHOSPHOR_PEAK[0], PHOSPHOR_PEAK[1], PHOSPHOR_PEAK[2], 0.85 * rim_alpha)
        ctx.set_line_width(2.2)
        ctx.rectangle(px_center - rim_w * 0.5, py_top, rim_w, rim_h)
        ctx.stroke()
        ctx.rectangle(px_center - tube_w * 0.5, py_top + rim_h, tube_w, (py_bot - py_top) - rim_h)
        ctx.stroke()

        # Dark interior opening mouth at the top rim so the Slime visibly dives inside!
        ctx.set_source_rgba(0.00, 0.03, 0.01, 0.96 * rim_alpha)
        ctx.rectangle(px_center - rim_w * 0.42, py_top + 2.0, rim_w * 0.84, 10.0)
        ctx.fill()

    ctx.restore()


